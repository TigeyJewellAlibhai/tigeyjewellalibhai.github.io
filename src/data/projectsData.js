export function getProjectBySlug(slug) {
  return projectEntries.find((project) => project.slug === slug)
}

export function getProjectsBySlugs(slugs) {
  return slugs
    .map((slug) => getProjectBySlug(slug))
    .filter(Boolean)
}

export function toProjectTile(project, sourceSection) {
  const externalCardHref = project.cardHref && project.cardHref !== '#' ? project.cardHref : undefined

  if (externalCardHref) {
    return {
      title: project.title,
      year: project.year,
      description: project.summary,
      image: project.image,
      href: externalCardHref,
    }
  }

  return {
    title: project.title,
    year: project.year,
    description: project.summary,
    image: project.image,
    to: `/projects/${project.slug}`,
    state: sourceSection ? { fromSection: sourceSection } : undefined,
  }
}
